#!/bin/sh
# A stand-in for pgbackrest in tests/pg/entry-test.sh: the commands and options the entry script and
# Postgres use (archive-push, archive-get, restore), with a directory as the repository
# ($STANDIN_REPO/<repo1-path>/<stanza>/{archive,base}). The restore writes the recovery settings the
# way pgBackRest does: recovery.signal, and restore_command and the target in postgresql.auto.conf.
# The repository path comes from --repo1-path, else STANDIN_REPO_PATH (the real one reads its config).
set -eu
repo=${STANDIN_REPO:?}
path=${STANDIN_REPO_PATH:-/default}
stanza= type= target= action= pg=
while [ $# -gt 0 ]; do
	case $1 in
	--stanza=*) stanza=${1#*=} ;;
	--repo1-path=*) path=${1#*=} ;;
	--pg1-path=*) pg=${1#*=} ;;
	--type=*) type=${1#*=} ;;
	--target=*) target=${1#*=} ;;
	--target-action=*) action=${1#*=} ;;
	--*) ;;
	*) break ;;
	esac
	shift
done
cmd=${1:?a command}
shift
[ -n "$stanza" ] || { echo "stand-in pgbackrest: no --stanza" >&2; exit 1; }
dir=$repo$path/$stanza
echo "$cmd stanza=$stanza path=$path $*" >>"$repo/calls"
case $cmd in
archive-push)
	mkdir -p "$dir/archive"
	f=$(basename "$1")
	if [ -f "$dir/archive/$f" ]; then
		cmp -s "$1" "$dir/archive/$f" && exit 0
		echo "stand-in pgbackrest: $f is already in the repository with other contents" >&2
		exit 1
	fi
	cp "$1" "$dir/archive/$f.tmp"
	mv "$dir/archive/$f.tmp" "$dir/archive/$f"
	;;
archive-get)
	[ -f "$dir/archive/$1" ] || exit 1
	cp "$dir/archive/$1" "$2"
	;;
restore)
	[ -d "$dir/base" ] && [ -n "$pg" ] || { echo "stand-in pgbackrest: no backup" >&2; exit 1; }
	cp -a "$dir/base/." "$pg/"
	touch "$pg/recovery.signal"
	{
		echo "# Recovery settings generated by pgBackRest restore (stand-in)"
		echo "restore_command = 'pgbackrest --repo1-path=$path --stanza=$stanza archive-get %f \"%p\"'"
		if [ "$type" = time ]; then
			echo "recovery_target_time = '$target'"
			echo "recovery_target_action = '${action:-pause}'"
		fi
	} >>"$pg/postgresql.auto.conf"
	;;
*)
	echo "stand-in pgbackrest: $cmd is not supported" >&2
	exit 1
	;;
esac
