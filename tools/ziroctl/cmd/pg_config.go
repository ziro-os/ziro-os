// Rendering a Postgres member: its container spec, tuned configuration and the small role file the
// agent keeps current. Everything here is a pure function of the cluster declaration, so the
// controller can re-render at any time and a member only restarts when its spec really changes.

//go:embed pg_entry.sh
var pgEntryScript string

// pgQuorum is how many replicas must acknowledge a commit when n replicas are in the synchronous
// set: 0 (asynchronous) below two replicas, one of two, and two of three or more. Two of three keeps
// both writes and a safe failover available with one replica down.
func pgQuorum(n int) int {
	switch {
	case n < 2:
		return 0
	case n == 2:
		return 1
	}
	return 2
}

// pgSyncSpec is the synchronous_standby_names value for a group ("" = asynchronous). Only replicas that
// have been ready count, so a new replica still copying its base backup cannot stall commits.
func pgSyncSpec(c *PGCluster, g *PGGroup) string {
	if c.Sync != pgSyncQuorum {
		return ""
	}
	var names []string
	for _, m := range g.Members {
		if m.Role == pgReplica && m.Joined && !m.Draining {
			names = append(names, m.ID)
		}
	}
	k := pgQuorum(len(names))
	if k == 0 {
		return ""
	}
	sort.Strings(names)
	return fmt.Sprintf("ANY %d (%s)", k, strings.Join(names, ", "))
}

// pgTuning is the postgresql.conf fragment for a member with the given limits. Memory-derived values
// follow the usual guidance (a quarter of memory for shared buffers, most of the rest as cache
// estimate); connections are kept modest because clients should go through a pooler.
func pgTuning(res *Resources, citus bool) string {
	mem := int64(1 << 30) // without a limit, tune for 1 GiB
	cpus := 2.0
	if res != nil {
		if b := res.MemoryBytes(); b > 0 {
			mem = b
		}
		if res.CPUs > 0 {
			cpus = res.CPUs
		}
	}
	const mi = int64(1 << 20)
	sharedBuffers := max(128*mi, min(mem/4, 32<<10*mi))
	maintenance := max(64*mi, min(mem/16, 2<<10*mi))
	maxConn := int64(200)
	workMem := max(4*mi, min((mem/4)/(maxConn*3), 64*mi))
	workers := int(max(2, min(int64(cpus*2), 64)))
	parallel := int(max(2, min(int64(cpus), 32)))
	gather := max(1, min(parallel/2, 4))
	walLevel := "replica"
	if citus {
		walLevel = "logical" // Citus moves shards with logical replication
	}
	var b strings.Builder
	set := func(k string, v any) { fmt.Fprintf(&b, "%s = %v\n", k, v) }
	mb := func(n int64) string { return strconv.FormatInt(n/mi, 10) + "MB" }
	b.WriteString("# Generated by ziroctl for this member's limits; rewritten on every start.\n")
	set("max_connections", maxConn)
	set("shared_buffers", mb(sharedBuffers))
	set("effective_cache_size", mb(mem*3/5))
	set("maintenance_work_mem", mb(maintenance))
	set("work_mem", mb(workMem))
	set("huge_pages", "try")
	set("password_encryption", "scram-sha-256")
	set("wal_level", walLevel)
	set("wal_compression", "on")
	set("wal_log_hints", "on")
	set("wal_buffers", "16MB")
	set("min_wal_size", "1GB")
	set("max_wal_size", "4GB")
	set("checkpoint_completion_target", 0.9)
	set("max_wal_senders", 20)
	set("max_replication_slots", 20)
	set("wal_keep_size", "512MB")
	set("max_slot_wal_keep_size", "8GB") // a replica gone for good cannot fill the primary's disk
	set("hot_standby", "on")
	set("hot_standby_feedback", "on")
	set("recovery_target_timeline", "latest")
	set("synchronous_commit", "on")
	set("random_page_cost", 1.1)
	set("effective_io_concurrency", 200)
	set("max_worker_processes", workers+4)
	set("max_parallel_workers", parallel)
	set("max_parallel_workers_per_gather", gather)
	set("tcp_keepalives_idle", 60)
	set("tcp_keepalives_interval", 10)
	set("tcp_keepalives_count", 6)
	set("log_checkpoints", "on")
	set("log_lock_waits", "on")
	set("log_min_duration_statement", "1000ms")
	set("shared_preload_libraries", "''")
	if citus {
		set("max_prepared_transactions", maxConn)
	}
	return b.String()
}

// pgRoleFile is the content of the role file: the one thing a restarting member needs to know.
func pgRoleFile(m *PGMember, g *PGGroup) string {
	role := pgReplica
	if m.Role == pgPrimary || m.Role == pgPromoting {
		role = pgPrimary
	}
	s := fmt.Sprintf("role=%s\nepoch=%d\n", role, g.Epoch)
	if m.Initialised {
		s += "initialised=1\n"
	}
	return s
}

// pgMemberApp is the cluster app that runs one member.
func pgMemberApp(st *ClusterState, c *PGCluster, g *PGGroup, m *PGMember) ClusteredApp {
	app := c.memberApp(g.Name, m.ID)
	image := c.Image
	if c.Citus != "" {
		image = c.Citus
	}
	from := c.dnsRW(g.Name) + "." + meshDomain
	if m.From != "" {
		if src := g.member(m.From); src != nil {
			from = "1." + c.memberApp(g.Name, src.ID) + "." + meshDomain
		}
	}
	env := map[string]string{
		"PGDATA":          pgDataPath + "/pgdata",
		"POSTGRES_USER":   c.User,
		"POSTGRES_DB":     c.Database,
		"ZIRO_PG_CLUSTER": c.Name,
		"ZIRO_PG_GROUP":   g.Name,
		"ZIRO_PG_MEMBER":  m.ID,
		"ZIRO_PG_INIT":    m.Init,
		"ZIRO_PG_FROM":    from,
		"ZIRO_PG_RW":      c.dnsRW(g.Name) + "." + meshDomain,
		"ZIRO_PG_SELF":    "1." + app + "." + meshDomain,
		"ZIRO_PG_NET":     podNetOf(st),
	}
	if c.Citus != "" {
		env["ZIRO_PG_CITUS"] = "1"
	}
	allow := []string{}
	for _, og := range c.Groups {
		for _, om := range og.Members {
			allow = append(allow, c.memberApp(og.Name, om.ID))
		}
	}
	allow = uniq(append(allow, c.AllowFrom...))
	sticky := true
	return ClusteredApp{
		Name: app, Image: image, Replicas: 1, Env: env, Args: []string{"bash", configMountPoint + "/entry.sh"},
		Secrets: []string{c.secretName()}, Data: []string{pgDataPath}, DataUID: pgDataUID, Resources: c.Resources,
		AllowFrom: allow, Node: m.Node, Sticky: &sticky, Replicated: true, StopTimeout: pgStopTimeout,
		ConfigFiles: map[string]string{"entry.sh": pgEntryScript, "postgresql.conf": pgTuning(c.Resources, c.Citus != "")},
	}
}

// podNetOf is the cluster pod network, the only place members accept connections from.
func podNetOf(st *ClusterState) string {
	if st.PodCIDR != "" {
		return st.PodCIDR
	}
	return "10.0.0.0/8"
}
